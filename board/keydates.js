/**
 * 수능까지 며칠 남았나. **지났으면 null** — 「D+3」은 아무 일도 돕지 않는다.
 * @return {?{date: string, days: number}}  days 0 = 당일
 */
export function suneungDday(now) {
  const s = KEY_DATES.find((k) => k.big);
  const days = Math.ceil((new Date(`${s.from}T00:00:00+09:00`) - (now || new Date())) / 86400000);
  return days >= 0 ? { date: s.from, days } : null;
}
