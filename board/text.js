/**
 * 화면에 쓰는 짧은 글자 다루기.
 * =====================================================================
 * 여러 화면이 같이 쓴다. 한 벌만 두는 까닭 — 조사 규칙이 두 벌이 되면
 * 한쪽만 고쳐지고, 화면에 `학부을(를)` 같은 표기가 남는다.
 */

/**
 * 받침을 보고 조사를 고른다.
 * 숫자·영문으로 끝나면 보수적으로 받침 있는 쪽을 쓴다 — 「AI를」보다 「AI을」이
 * 어색하지만, 읽는 데 걸리지는 않는다. 반대는 문장이 깨진 것처럼 보인다.
 */
export function josa(word, withBatchim, without) {
  /*
   * 뒤에 붙은 괄호·따옴표는 떼고 본다. 「교과(지역인재)」 의 마지막 글자는 `)` 지만
   * 소리 내어 읽을 때는 `재` 로 끝난다. 안 떼면 「교과(지역인재)」은 이 된다.
   */
  const last = String(word || '').trim().replace(/[)\]}」』"'’”.·]+$/, '').slice(-1);
  if (!last) return withBatchim;
  /*
   * **「로/으로」만 규칙이 다르다.** ㄹ 받침은 받침이 없는 것처럼 「로」를 쓴다 —
   * 「서울로」이지 「서울으로」가 아니다. 「면접으로」는 ㅂ 받침이라 그대로 「으로」다.
   * 은/는·이/가·을/를에는 이 예외가 없으니 「로」를 부를 때만 본다.
   */
  const RIEUL = 8;
  const code = last.charCodeAt(0);
  if (code >= 0xac00 && code <= 0xd7a3) {
    const jong = (code - 0xac00) % 28;
    if (!jong) return without;
    if (jong === RIEUL && without === '로') return without;
    return withBatchim;
  }

  /*
   * **숫자·로마숫자·알파벳은 소리 내어 읽은 뒤 받침을 본다.**
   *
   * 「종합(미래인재2)」는 「미래인재이」로 읽히니 받침이 없다 — 「2가 뒤를 잇습니다」다.
   * 「1」은 「일」이라 받침이 있다. 여태 한글이 아니면 무조건 받침이 있는 쪽을 골라서
   * 전형이 쪼개진 카드마다 「미래인재2이」가 찍혔다.
   *
   * 입결과 모집요강의 전형·학과 이름 6,716가지 가운데 한글이 아닌 글자로 끝나는 것이
   * 130가지(1.9%)다 — 로마숫자 42 · 숫자 42 · 알파벳 46. 드물지만 하필 전형이
   * 쪼개진 이름(`미래인재1` `교과우수Ⅱ`)에 몰려 있어서 이 카드들에서 늘 눈에 띈다.
   *
   * 받침이 있는 것만 적는다 — 일 삼 육 칠 팔 / F(에프) L(엘) M(엠) N(엔) R(아르)
   * S(에스) X(엑스). 나머지는 받침이 없다.
   */
  const READ_BATCHIM = /[13678FLMNRSXflmnrsx]|[ⅠⅢⅰⅲ]/;
  if (/[0-9A-Za-zⅠⅡⅢⅣⅤⅰⅱⅲ]/.test(last)) {
    return READ_BATCHIM.test(last) ? withBatchim : without;
  }
  return withBatchim;
}

/**
 * 경쟁률 한 줄 — **소수 첫째 자리로 못박는다.**
 *
 * 입결의 경쟁률 칸이 원본에서 이미 나눗셈 결과로 들어와 있는 줄이 있다.
 * 75,592줄 가운데 528줄이 `7.333333333333333` 꼴이라, 그대로 찍으면 카드에
 * 「경쟁률 5.490566037735849:1」이 나온다. 좁은 칸을 밀어내고 무엇보다
 * 읽을 수가 없다 — 상담에서 필요한 것은 「5.5 대 1」이지 그 뒤가 아니다.
 *
 * 실질경쟁률(명목 × 모집 ÷ (모집+추합))과 학생이 적는 최종 경쟁률도 같은 꼴이
 * 될 수 있어서, **경쟁률을 찍는 자리는 전부 여기를 지난다.**
 */
export function rate1(v) {
  if (v == null || v === '') return null;
  const n = Number(v);
  return Number.isFinite(n) ? n.toFixed(1) : null;
}

/**
 * 서버가 준 날짜를 「yyyy-MM-dd」로 못박는다.
 *
 * 구글 시트가 날짜 칸을 Date 로 바꿔 버리면 옛 배포의 서버는 그걸 UTC 로 적어
 * 「2026-11-27T15:00:00.000Z」— 하루 전 날짜에 시각이 붙은 값을 준다. 서버는
 * 고쳤지만(cell_) 선생님이 새 배포를 하기 전까지 옛 서버가 살아 있다.
 * 받는 쪽에서도 씻어야 그 사이에 면접일이 화면에서 사라지지 않는다.
 * +9시간은 KST 다 — 이 도구는 한국 학사 일정만 다룬다.
 */
export function isoDay(v) {
  const s = String(v || '').trim();
  if (!s || /^\d{4}-\d{2}-\d{2}$/.test(s)) return s;
  const t = Date.parse(s);
  if (Number.isNaN(t)) return s;
  return new Date(t + 9 * 3600 * 1000).toISOString().slice(0, 10);
}

/**
 * 수능 최저 기준 글을 「3합 12」 꼴로 줄인다. **못 줄이면 null 이다.**
 *
 * 기준 글 465가지를 다 넣고 쟀다. 「N개 영역 등급 합 M」 꼴이 대부분이고,
 * 「N개 영역 각 M등급」·「N개 영역 M등급 이내」가 그 다음이다. 셋을 합치면
 * **91%가 한 가지 요약으로 떨어진다.** 나머지는 요약하지 않는다 —
 *
 *   여러 값이 나오는 글   의예과 분기·계열 분기("의학과는 합 5") — 하나만 고르면 거짓말
 *   1개 영역의 「합」      수학과 탐구평균을 묶은 특수형 — 「1합 4」는 오해를 만든다
 *   못 읽는 글           "수학+과탐 등급 합 3" 따위 34가지 — 억지로 읽지 않는다
 *
 * null 이면 부르는 쪽이 「수능 최저 있음」으로 두고, 원문은 상세에 그대로 있다.
 * **오표기가 미표기보다 나쁘다** — 컷 연결과 같은 원칙이다.
 */
const MIN_SUM = /([2-4])\s*개\s*(?:영역|과목)?\s*(?:의)?\s*(?:등급)?\s*(?:의)?\s*합(?:이)?\s*([0-9]{1,2})/g;
const MIN_EACH = /([1-4])\s*개\s*(?:영역|과목)?\s*각(?:각)?\s*([1-9])\s*등급/g;
const MIN_ONE = /([1-4])\s*개\s*영역(?:의)?\s*(?:등급)?(?:이)?\s*([1-9])\s*(?:등급)?\s*이내/g;

export function minReqShort(text) {
  const t = String(text || '');
  if (!t.trim()) return null;
  const hits = [
    ...[...t.matchAll(MIN_SUM)].map((m) => `${m[1]}합 ${m[2]}`),
    ...[...t.matchAll(MIN_EACH)].map((m) => `${m[1]}개 각 ${m[2]}등급`),
    ...[...t.matchAll(MIN_ONE)].map((m) => `${m[1]}개 ${m[2]}등급`),
  ];
  const uniq = [...new Set(hits)];
  return uniq.length === 1 ? uniq[0] : null;
}
