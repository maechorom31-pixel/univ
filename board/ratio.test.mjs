/**
 * 올해 최종 경쟁률 잇기 시험
 * =====================================================================
 *   node board/ratio.test.mjs
 *
 * 여기 있는 대학·학과 이름은 실제 자료의 모양을 본뜬 것이고, 학생 자료는 없다.
 *
 * 이 시험이 지키는 것은 하나다 — **안 붙어야 할 것이 안 붙는가.**
 * 붙는 쪽이 한둘 모자란 것은 담임이 카드에서 적으면 그만이지만, 옆 전형이나
 * 옆 학과의 숫자가 붙으면 종이에 틀린 숫자가 실리고 아무 데도 그렇게 안 적힌다.
 * 그래서 통과 조건이 「맞는 것을 많이 붙인다」가 아니라 「틀린 것을 안 붙인다」다.
 */
import { indexRatio, rateOf, splitUniv, normTrack, normUnit, kindOf, typeOnly } from './ratio.js';

let fails = 0;
const eq = (got, want, label) => {
  if (JSON.stringify(got) !== JSON.stringify(want)) {
    console.log(`  ✗ ${label}\n      받음 ${JSON.stringify(got)}\n      기대 ${JSON.stringify(want)}`);
    fails++;
  } else console.log(`  ✓ ${label}`);
};

/* ── 만들기 ──────────────────────────────────────────────────────── */

/** 대학 한 곳. 전형마다 [모집단위, 모집, 지원, 경쟁률] 줄을 준다. */
const U = (u, final, tracks) => ({
  u, stamp: '2026-09-11T17:30', final, deadline: '', t:
    Object.entries(tracks).map(([n, r]) => ({ n, k: kindOf(n), r })),
});

const DOC = {
  built: '2026-09-11T17:40',
  univs: [
    U('전남대학교', true, {
      '광주캠퍼스 학생부교과(일반)': [['경영학부', 55, 341, 6.2], ['간호학과', 10, 41, 4.1],
        ['건축학부', 4, 30, 7.5], ['건축학부(건축공학전공)', 10, 45, 4.5]],
      '광주캠퍼스 학생부교과(지역인재)': [['간호학과', 30, 90, 3.0]],
      '광주캠퍼스 학생부종합(고교생활우수자Ⅰ)': [['경영학부', 20, 140, 7.0]],
      '여수캠퍼스 학생부교과(일반)': [['경영학과', 20, 60, 3.0]],
    }),
    U('고려대학교(서울)', true, {
      '서울캠퍼스 학생부교과(학교추천전형)': [['경영학과', 54, 297, 5.5]],
    }),
    U('고려대학교(세종)', false, {
      '학생부교과(일반전형)': [['경영학과', 20, 100, 5.0]],
    }),
    U('상명대학교서울캠퍼스', true, {
      '학생부교과(고교추천)': [['인문콘텐츠학부(역사콘텐츠전공)', 5, 30, 6.0]],
    }),
    U('송원대학교', true, {
      '학생부교과(면접우수자면접전형)': [['간호학과', 141, 400, 2.84]],
    }),
    U('배재대학교', true, {
      '학생부교과': [['간호학과', 20, 100, 5.0]],
      '학생부종합': [['간호학과', 10, 70, 7.0]],
    }),
    U('우송대학교', true, {
      '일반전형': [['간호학과', 20, 100, 5.0], ['간호학과', 10, 40, 4.0]],
    }),
    U('원광대학교', false, {
      '학생부교과(교과일반)': [['간호학과', 30, 90, 3.0]],
    }),
  ],
  dropped: [{ u: '홍익대학교', why: '한 번 수집한 것에 같은 이름이 2장이라 캠퍼스를 가릴 수 없습니다' }],
};

const IX = indexRatio(DOC);

const app = (univ, dept, typeSub, opts = {}) => ({
  id: `${univ}|${dept}|${typeSub}`, univ, dept, typeSub,
  typeName: opts.typeName != null ? opts.typeName : typeSub,
  typeCat: opts.cat != null ? opts.cat : '학생부위주(교과)',
  quota: opts.quota == null ? null : opts.quota,
});
const got = (a) => rateOf(IX, a);

/* ── 이름 고르기 ─────────────────────────────────────────────────── */

console.log('대학 이름은 몸통과 캠퍼스로 가른다');
eq(splitUniv('건국대학교서울캠퍼스'), { base: '건국대', campus: '서울' }, '「…대학교서울캠퍼스」');
eq(splitUniv('전남대학교(광주)'), { base: '전남대', campus: '광주' }, '괄호 캠퍼스');
eq(splitUniv('한양대학교(ERICA)'), { base: '한양대', campus: 'ERICA' }, '로마자 캠퍼스');
eq(splitUniv('국립순천대학교'), { base: '순천대', campus: '' }, '「국립」은 뗀다');
eq(splitUniv('이화여자대학교'), { base: '이화여대', campus: '' }, '「여자대」는 「여대」');
eq(splitUniv('한국외국어대학교(서울)'), { base: '한국외대', campus: '서울' }, '한국외대');

console.log('전형 이름에서 유형은 뺀다 — 유형은 따로 맞춘다');
eq(normTrack('광주캠퍼스 학생부교과(일반)'), '일반', '캠퍼스·유형·괄호를 뗀 뒤');
eq(normTrack('교과(일반)'), '일반', '즐겨찾기가 줄여 적은 것도 같은 꼴이 된다');
eq(normTrack('종합(고교생활우수자Ⅰ)'), '고교생활우수자1', '로마숫자는 아라비아로');
eq(typeOnly('학생부교과'), true, '유형뿐인 이름');
eq(typeOnly('학생부교과(일반)'), false, '이름이 있는 전형');

console.log('모집단위는 괄호 안까지 본다');
eq(normUnit('건축학부(건축공학전공)'), '건축학부·건축공학', '괄호를 가운뎃점으로');
eq(normUnit('AI·SW학부 (인공지능공학전공)'), 'AI·SW학부·인공지능공학', '띄어쓰기·가운뎃점');
eq(normUnit('건축학부') === normUnit('건축학부(건축공학전공)'), false, '학부와 그 안 전공은 다르다');

/* ── 붙는 것 ─────────────────────────────────────────────────────── */

console.log('정확히 맞으면 붙는다');
{
  const r = got(app('전남대학교(광주)', '경영학부', '교과(일반)', { quota: 55 }));
  eq(r.ok, true, '전남대 광주 교과(일반) 경영학부');
  eq(r.rate, 6.2, '그 줄의 경쟁률');
  eq(r.final, true, '대학이 「최종」이라 적은 자료');
}
{
  const r = got(app('전남대학교(여수)', '경영학과', '교과(일반)'));
  eq(r.ok && r.rate, 3.0, '캠퍼스가 다르면 그 캠퍼스의 전형에서 찾는다');
}
{
  const r = got(app('고려대학교(서울)', '경영학과', '학생부교과(학교추천전형)', { quota: 54 }));
  eq(r.ok && r.rate, 5.5, '캠퍼스가 여럿인 대학 — 표기가 같은 쪽');
}
{
  const r = got(app('상명대학교(서울)', '인문콘텐츠학부(역사콘텐츠전공)', '학생부교과(고교추천)'));
  eq(r.ok && r.rate, 6.0, '「…서울캠퍼스」와 「…(서울)」은 같은 대학');
}
{
  const r = got(app('송원대학교', '간호학과', '학생부교과(면접우수자면접전형)', { quota: 141 }));
  eq(r.ok && r.rate, 2.84, '전형 이름이 긴 것도 그대로 맞춘다');
}
{
  const r = got(app('원광대학교', '간호학과', '교과(교과일반)'));
  eq(r.ok, true, '아직 최종이 아닌 대학도 잇기는 한다');
  eq(r.final, false, '다만 최종이 아니라고 적어 준다 — 종이에는 싣지 않는다');
}

/* ── 안 붙는 것 ──────────────────────────────────────────────────── */

console.log('섞일 수 있으면 붙이지 않는다');
{
  const r = got(app('전남대학교(광주)', '간호학과', '교과(지역인재)'));
  eq(r.ok && r.rate, 3.0, '지역인재는 지역인재 줄에서만 — 일반 줄의 4.1 이 아니다');
}
{
  const r = got(app('전남대학교(광주)', '간호학과', '교과(사회배려)'));
  eq(r.ok, false, '자료에 없는 전형(사회배려)');
  eq(r.reason, 'track', '사유는 전형');
}
{
  const r = got(app('전남대학교(광주)', '컴퓨터공학부', '교과(일반)'));
  eq(r.ok, false, '자료에 없는 모집단위');
  eq(r.reason, 'unit', '사유는 모집단위');
}
{
  const r = got(app('전남대학교(광주)', '경영학부', '교과(일반)', { quota: 40 }));
  eq(r.ok, false, '모집인원이 어긋나면 다른 줄을 본 것일 수 있다');
  eq(r.reason, 'quota', '사유는 모집인원');
}
{
  const r = got(app('고려대학교', '경영학과', '학생부교과(학교추천전형)'));
  eq(r.ok, false, '캠퍼스를 안 적은 고려대 — 서울인지 세종인지 모른다');
  eq(r.reason, 'univ', '사유는 대학');
}
{
  const r = got(app('홍익대학교(서울)', '컴퓨터공학과', '교과(학교장추천자)'));
  eq(r.ok, false, '자료에서 뺀 대학(같은 이름의 페이지가 둘)');
  eq(r.note.includes('캠퍼스'), true, '왜 없는지 사유가 따라온다');
}
{
  const r = got(app('우송대학교', '간호학과', '일반전형'));
  eq(r.ok, false, '같은 이름의 모집단위가 둘이면 어느 줄인지 모른다');
  eq(r.reason, 'unit', '사유는 모집단위');
}
{
  const r = got(app('배재대학교', '간호학과', '학생부교과', { cat: '학생부위주(교과)' }));
  eq(r.ok && r.rate, 5.0, '이름이 유형뿐이면 그 유형의 전형이 하나일 때만 붙인다');
}
{
  const r = got(app('배재대학교', '간호학과', '', { cat: '', typeName: '' }));
  eq(r.ok, false, '전형 이름도 유형도 비었으면 교과인지 종합인지 고를 수 없다');
  eq(r.reason, 'track', '사유는 전형');
}
{
  const r = got(app('전남대학교(광주)', '경영학부', '교과(일반)', { quota: 55 }));
  eq(r.univ, '전남대학교', '어느 자료에서 왔는지 적어 준다');
  eq(r.track, '광주캠퍼스 학생부교과(일반)', '어느 전형 줄인지');
  eq(r.unit, '경영학부', '어느 모집단위 줄인지');
}

console.log('자료가 없으면 조용히 비운다');
eq(rateOf(null, app('전남대학교(광주)', '경영학부', '교과(일반)')).reason, 'data',
  '아직 못 받았다고 말한다');

console.log(fails ? `\n${fails}건 실패` : '\n모두 통과');
process.exit(fails ? 1 : 0);
