/**
 * 화면에 쓰는 짧은 글자 다루기.
 * =====================================================================
 * 여러 화면이 같이 쓴다. 한 벌만 두는 까닭 — 조사 규칙이 두 벌이 되면
 * 한쪽만 고쳐지고, 화면에 `학부을(를)` 같은 표기가 남는다.
 */

/**
 * 받침을 보고 조사를 고른다.
 * 숫자·영문으로 끝나면 보수적으로 받침 있는 쪽을 쓴다 — 「AI를」보다 「AI을」이
 * 어색하지만, 읽는 데 걸리지는 않는다. 반대는 문장이 깨진 것처럼 보인다.
 */
export function josa(word, withBatchim, without) {
  /*
   * 뒤에 붙은 괄호·따옴표는 떼고 본다. 「교과(지역인재)」 의 마지막 글자는 `)` 지만
   * 소리 내어 읽을 때는 `재` 로 끝난다. 안 떼면 「교과(지역인재)」은 이 된다.
   */
  const last = String(word || '').trim().replace(/[)\]}」』"'’”.·]+$/, '').slice(-1);
  if (!last) return withBatchim;
  /*
   * **「로/으로」만 규칙이 다르다.** ㄹ 받침은 받침이 없는 것처럼 「로」를 쓴다 —
   * 「서울로」이지 「서울으로」가 아니다. 「면접으로」는 ㅂ 받침이라 그대로 「으로」다.
   * 은/는·이/가·을/를에는 이 예외가 없으니 「로」를 부를 때만 본다.
   */
  const RIEUL = 8;
  const code = last.charCodeAt(0);
  if (code >= 0xac00 && code <= 0xd7a3) {
    const jong = (code - 0xac00) % 28;
    if (!jong) return without;
    if (jong === RIEUL && without === '로') return without;
    return withBatchim;
  }

  /*
   * **숫자·로마숫자·알파벳은 소리 내어 읽은 뒤 받침을 본다.**
   *
   * 「종합(미래인재2)」는 「미래인재이」로 읽히니 받침이 없다 — 「2가 뒤를 잇습니다」다.
   * 「1」은 「일」이라 받침이 있다. 여태 한글이 아니면 무조건 받침이 있는 쪽을 골라서
   * 전형이 쪼개진 카드마다 「미래인재2이」가 찍혔다.
   *
   * 입결과 모집요강의 전형·학과 이름 6,716가지 가운데 한글이 아닌 글자로 끝나는 것이
   * 130가지(1.9%)다 — 로마숫자 42 · 숫자 42 · 알파벳 46. 드물지만 하필 전형이
   * 쪼개진 이름(`미래인재1` `교과우수Ⅱ`)에 몰려 있어서 이 카드들에서 늘 눈에 띈다.
   *
   * 받침이 있는 것만 적는다 — 일 삼 육 칠 팔 / F(에프) L(엘) M(엠) N(엔) R(아르)
   * S(에스) X(엑스). 나머지는 받침이 없다.
   */
  const READ_BATCHIM = /[13678FLMNRSXflmnrsx]|[ⅠⅢⅰⅲ]/;
  if (/[0-9A-Za-zⅠⅡⅢⅣⅤⅰⅱⅲ]/.test(last)) {
    return READ_BATCHIM.test(last) ? withBatchim : without;
  }
  return withBatchim;
}
